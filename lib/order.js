// Дробный индекс порядка карточек.
//
// Наивный подход хранит целочисленный индекс, и перетаскивание карточки в
// начало колонки из десяти строк требует переписать все десять. Здесь порядок
// хранится строкой, а новое значение выдаётся МЕЖДУ двумя соседями, поэтому
// перетаскивание — всегда один UPDATE одной строки, сколько бы карточек ни
// было в колонке.
//
// Реализация строковая намеренно. Вариант на числах с плавающей точкой
// проходит поверхностную проверку и разваливается примерно на пятидесятой
// вставке в одно и то же место, когда кончается разрядность.
//
// Ключ читается как дробь после подразумеваемого «0.»: сравнение обычное
// лексикографическое. Ключ никогда не заканчивается первым символом алфавита —
// иначе следующее деление слева стало бы невозможным.

/** Алфавит в порядке возрастания кодов символов. */
const DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'
const FIRST = DIGITS[0]

/** Значение строго между `a` и `b`; `b === undefined` означает «до конца». */
function midpoint(a, b) {
  if (b !== undefined && a >= b) {
    throw new Error(`порядок нарушен: ${JSON.stringify(a)} не меньше ${JSON.stringify(b)}`)
  }
  if (a.endsWith(FIRST) || (b !== undefined && b.endsWith(FIRST))) {
    throw new Error('ключ порядка не может заканчиваться первым символом алфавита')
  }

  if (b !== undefined) {
    // Общий префикс переносится в результат как есть, деление продолжается на
    // остатке — иначе для близких соседей пришлось бы наращивать длину с нуля.
    let n = 0
    while ((a[n] ?? FIRST) === b[n]) n += 1
    if (n > 0) return b.slice(0, n) + midpoint(a.slice(n), b.slice(n))
  }

  const from = a === '' ? 0 : DIGITS.indexOf(a[0])
  const to = b === undefined ? DIGITS.length : DIGITS.indexOf(b[0])
  if (from < 0 || to < 0) throw new Error('ключ порядка содержит символ вне алфавита')

  if (to - from > 1) {
    return DIGITS[Math.round(0.5 * (from + to))]
  }
  if (b !== undefined && b.length > 1) {
    return b.slice(0, 1)
  }
  // Соседние символы: занимаем разряд `a` и делим следующий.
  return DIGITS[from] + midpoint(a.slice(1), undefined)
}

/**
 * Ключ порядка строго между двумя соседями.
 *
 * Оба соседа необязательны: без обоих выдаётся стартовое значение, без правого
 * — значение после `a`, без левого — значение перед `b`. Результат всегда
 * можно снова разделить.
 *
 * @param {string} [a] ключ карточки слева
 * @param {string} [b] ключ карточки справа
 * @returns {string} ключ строго между ними
 * @throws если `a` не меньше `b` либо ключ содержит символ вне алфавита
 */
export function keyBetween(a, b) {
  return midpoint(a ?? '', b ?? undefined)
}
